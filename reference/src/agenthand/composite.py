def _validate_receipt(receipt: object) -> tuple[list[str], list[str]]:
    """Shape and terms validation for a fidelity receipt.

    Returns (shape_problems, term_problems); both empty means the
    receipt is well-formed and states the contract terms. This is
    the fail-closed front door of verify_receipt_from_disk: a
    truncated, nulled, or retyped receipt is an INVALID receipt (a
    structured failure), never an exception, and never an excuse to
    grade under weaker rules. (The badass Gauntlet reproduced the
    pre-hardening behaviour three times over: dropping any of
    several fields raised KeyError, a nulled opaque_fraction raised
    TypeError, and loosened term fields were accepted as
    decoration.)

    Compatibility policy for historical receipts: a receipt stamped
    with the current schema version must carry every contract field.
    A receipt with NO schema marker is the v1 shape issued before
    the contract fields existed (the frozen 2026-10-26 replay
    receipt is the live example): it is graded on the fields it
    carries, which the grader recounts from disk under the contract
    terms regardless. A v1 receipt that DOES state term fields is
    held to them exactly — the policy covers silence, never a
    loosened statement. Any other schema marker fails closed.
    """
    shape: list[str] = []
    terms: list[str] = []
    if not isinstance(receipt, dict):
        return (
            [f"receipt is a {type(receipt).__name__}, not a JSON object"],
            terms,
        )
    schema = receipt.get("receipt_schema")
    if schema is None:
        version = 1
    elif type(schema) is int and schema in (2, 3, RECEIPT_SCHEMA_VERSION):
        version = schema
    else:
        version = 0
        shape.append(
            f"unsupported receipt_schema {schema!r}; this verifier "
            f"grades schema 2, 3 and {RECEIPT_SCHEMA_VERSION} receipts "
            "and unmarked v1 receipts"
        )
    strict = version >= 2
    if version == 1 and any(name in receipt for name in _V2_ONLY_FIELDS):
        # Downgrade guard: dropping or nulling the schema marker of
        # a current receipt must not buy it the legacy policy. A
        # genuine v1 receipt carries none of the v2-only fields
        # (mask_asset is NOT one of them: v1 receipts name the mask
        # asset, they just do not pin its hashes).
        shape.append(
            "receipt carries current-schema fields but no valid "
            "receipt_schema marker; refusing to grade it under the "
            "legacy v1 policy"
        )
    if 0 < version < 3 and "reconstruction" in receipt:
        # The same guard one schema up: paper disclosed on a receipt
        # graded under the v2 policy would be carried as an ignored
        # extra field, which is exactly the blind spot schema 3
        # exists to close.
        shape.append(
            "receipt carries a reconstruction block but is not "
            "marked schema 3; refusing to grade reconstruction "
            "under an older policy"
        )
    recon_policy = receipt.get("reconstruction")
    v4_reconstruction = isinstance(recon_policy, dict) and any(
        k in recon_policy for k in ("policy_version", "max_fraction", "attempted")
    )
    if 0 < version < 4 and (
        any(k in receipt for k in ("cut_quality", "plate_quality")) or v4_reconstruction
    ):
        shape.append("receipt carries schema-4 quality fields under an older policy")
    fields = dict(_RECEIPT_FIELDS_ANY_SCHEMA)
    if version >= 2:
        fields.update(_RECEIPT_FIELDS_V2)
    if version >= 3:
        fields.update(_RECEIPT_FIELDS_V3)
    if version >= 4:
        fields.update(_RECEIPT_FIELDS_V4)
    for name, valid in fields.items():
        if name not in receipt:
            shape.append(f"missing field: {name}")
        elif not valid(receipt[name]):
            shape.append(f"field {name} has the wrong type or shape: {receipt[name]!r}")
    if strict:
        # Optional provenance fields: validated when present.
        for name, valid in _RECEIPT_FIELDS_V2_OPTIONAL.items():
            if name in receipt and not valid(receipt[name]):
                shape.append(
                    f"field {name} has the wrong type or shape: {receipt[name]!r}"
                )
    if shape:
        return shape, terms
    if version >= 4:
        if receipt["plate_kind"] == "local_placeholder":
            if (
                receipt["plate_source"] != "local_placeholder"
                or receipt["plate_asset"] is not None
                or receipt["plate_sha256"] is not None
                or receipt["plate_pixel_sha256"] is not None
                or receipt["backdrop"] is not None
            ):
                shape.append("local placeholder provenance is inconsistent")
        elif (
            receipt["plate_source"] != "asset"
            or not receipt["plate_asset"]
            or not receipt["plate_sha256"]
            or not receipt["plate_pixel_sha256"]
        ):
            shape.append("asset plate provenance is incomplete")
        if receipt["plate_kind"] == "code_rendered" and not receipt["backdrop"]:
            shape.append("code-rendered plate requires its backdrop specification")
        if (
            receipt["plate_kind"] == "model_generated"
            and receipt["backdrop"] is not None
        ):
            shape.append("model plate cannot claim a code backdrop")
        if shape:
            return shape, terms
    # Internal consistency of the stated counts: a receipt whose own
    # numbers disagree with each other is forged or torn, whatever
    # the files say.
    if (
        receipt["mask_pixels_total"]
        != receipt["opaque_pixels"] + receipt["edge_band_pixels"]
    ):
        shape.append("mask_pixels_total != opaque_pixels + edge_band_pixels")
    if receipt["changed_opaque_pixels"] > receipt["opaque_pixels"]:
        shape.append("changed_opaque_pixels exceeds opaque_pixels")
    total = receipt["mask_pixels_total"]
    if total:
        expected_fraction = round(receipt["opaque_pixels"] / total, 6)
        if abs(float(receipt["opaque_fraction"]) - expected_fraction) > 1e-9:
            shape.append(
                "opaque_fraction disagrees with opaque_pixels / mask_pixels_total"
            )
    elif float(receipt["opaque_fraction"]) != 0.0:
        shape.append("opaque_fraction is nonzero while mask_pixels_total is 0")
    if version >= 3:
        # The reconstruction block's own arithmetic: status, assets,
        # region counts, and the fraction must tell one story.
        block = receipt["reconstruction"]
        region_sum = sum(r["pixels"] for r in block["regions"])
        if block["reconstruction_overlap_product_pixels"] != 0:
            shape.append(
                "reconstruction_overlap_product_pixels must be 0; "
                "paper on product pixels is not a weaker claim, it "
                "is a broken one"
            )
        if region_sum != block["reconstruction_pixels"]:
            shape.append("reconstruction regions do not sum to reconstruction_pixels")
        if block["status"] == "applied":
            if block["layer_asset"] is None or block["reconstruction_pixels"] == 0:
                shape.append(
                    "reconstruction status is 'applied' but no "
                    "layer asset or no paper pixels are claimed"
                )
            recon_total = block["reconstruction_pixels"] + receipt["opaque_pixels"]
            expected_recon = (
                round(block["reconstruction_pixels"] / recon_total, 6)
                if recon_total
                else 0.0
            )
            if abs(float(block["reconstruction_fraction"]) - expected_recon) > 1e-9:
                shape.append(
                    "reconstruction_fraction disagrees with "
                    "reconstruction_pixels / (reconstruction_pixels "
                    "+ opaque_pixels)"
                )
        elif block["layer_asset"] is not None or block["reconstruction_pixels"] != 0:
            shape.append(
                f"reconstruction status is {block['status']!r} but "
                "a layer asset or paper pixels are claimed"
            )
    if strict:
        if receipt["mask_source"] == "asset" and receipt["mask_asset"] is None:
            shape.append("mask_source is 'asset' but mask_asset is null")
        if (
            receipt["mask_source"] == "foreground_alpha"
            and receipt["mask_asset"] is not None
        ):
            shape.append("mask_source is 'foreground_alpha' but mask_asset is set")
    if strict and any(name in receipt for name in _RECEIPT_FIELDS_V2_OPTIONAL):
        # Mask provenance is an all-or-nothing, self-consistent
        # statement: a partial or contradictory set is a forged or
        # torn receipt, not a weaker claim.
        missing = [name for name in _RECEIPT_FIELDS_V2_OPTIONAL if name not in receipt]
        if missing:
            shape.append(
                "mask provenance is partial; missing fields: "
                + ", ".join(sorted(missing))
            )
        else:
            if (
                receipt["mask_sam_width"] > receipt["mask_source_width"]
                or receipt["mask_sam_height"] > receipt["mask_source_height"]
            ):
                shape.append(
                    "mask SAM frame exceeds the mask source frame; the "
                    "SAM-bound copy is only ever downscaled"
                )
            unscaled = (
                receipt["mask_sam_width"] == receipt["mask_source_width"]
                and receipt["mask_sam_height"] == receipt["mask_source_height"]
            )
            if (receipt["mask_scale_method"] == "none") != unscaled:
                shape.append(
                    "mask_scale_method disagrees with the recorded "
                    "SAM and source frames"
                )
    # Stated terms are law in every schema: present term fields must
    # equal the contract exactly; the current schema must state them.
    for name, expected in _RECEIPT_TERMS.items():
        if name in receipt:
            if receipt[name] != expected or isinstance(receipt[name], bool):
                terms.append(
                    f"{name} is {receipt[name]!r}; the contract term "
                    f"is {expected!r} and receipts are graded only "
                    "under it"
                )
        elif strict:
            terms.append(f"missing term field: {name}")
    return shape, terms


def verify_receipt_from_disk(
    store: AssetStore, composite_handle: str, receipt: dict | None = None
) -> dict:
    """Independently re-verify a draw receipt from the stored FILES.

    The receipt draw returns is computed by the compositor, in memory,
    at draw time — the J2 Gauntlet's "self-graded receipt" objection.
    This is the independent path: it re-reads the stored source,
    foreground, and composite files from disk, re-checks every file
    against its recorded hashes, decodes the pixels fresh, recounts
    the changed opaque pixels, and re-derives the colour-profile
    identities. Nothing is taken from the receipt except the claims
    being checked and the handles of the assets it names.

    The receipt may be omitted: draw persists it beside the composite
    (``<asset_id>.receipt.json`` in the asset store) and it is loaded
    from there, so a composite found in the store carries the claims
    to check with it. A receipt supplied by the caller takes
    precedence over the persisted one. Receipts persisted by the
    server carry extra billing fields (cost, call attribution); only
    the fidelity fields are read here. ValueError is raised when no
    receipt is supplied and none is persisted for the composite.

    Returns a report dict: ``ok`` (True only when every check passes),
    ``checks`` (per-check booleans), ``problems`` (human-readable
    failures), and ``recomputed`` (the from-disk measurements). A
    tampered stored file, a recount that disagrees with the receipt,
    or a colour profile that differs between the source photo and the
    delivered composite all make ``ok`` False — they never raise, so a
    caller (the standalone verifier, the film's on-camera check) gets
    the full list of what is wrong. KeyError propagates for an unknown
    composite handle.

    A pass additionally requires the receipt's own file and pixel
    hashes to match the records of the assets it names (a receipt
    cannot verify a different run's composite), exactly zero changed
    opaque pixels (a receipt honestly reporting a change must fail),
    and positive opaque coverage (a receipt covering no product
    pixels vouches for nothing). Architecture Gauntlet fix 2.

    The receipt itself is never trusted and never crashes the check
    (badass Gauntlet, converged item 1): its shape and stated terms
    are validated first (_validate_receipt), the mask FILE is
    re-hashed against its record like every other file, and every
    failure the receipt's content can cause — missing, nulled, or
    retyped fields, loosened terms, handles naming assets that do
    not exist, undecodable files — returns as a failed check in the
    report. Only the caller's own composite handle may raise
    KeyError, as documented above.
    """
    if receipt is None:
        receipt = store.load_receipt(composite_handle)
        if receipt is None:
            raise ValueError(
                f"No receipt supplied and none persisted beside "
                f"{composite_handle!r}; there are no claims to verify."
            )
    checks: dict[str, bool] = {}
    problems: list[str] = []
    recomputed: dict = {}

    def check(name: str, ok: bool, detail: str = "") -> None:
        checks[name] = bool(ok)
        if not ok:
            problems.append(f"{name}: {detail}" if detail else name)

    def report() -> dict:
        return {
            "ok": all(checks.values()),
            "checks": checks,
            "problems": problems,
            "recomputed": recomputed,
            "composite_asset": composite_handle,
            "foreground_asset": (
                receipt.get("foreground_asset") if isinstance(receipt, dict) else None
            ),
            "source_asset": (
                receipt.get("source_asset") if isinstance(receipt, dict) else None
            ),
        }

    # 0. The receipt's shape and terms, before anything is read from
    #    it: malformed content fails here, structurally.
    shape_problems, term_problems = _validate_receipt(receipt)
    check("receipt_shape", not shape_problems, "; ".join(shape_problems))
    check("receipt_terms", not term_problems, "; ".join(term_problems))
    if shape_problems or term_problems:
        return report()

    composite_record = store.get_record(composite_handle)
    # The policy marker travels inside the hash-pinned delivered PNG, so
    # deleting every v4 receipt field cannot opt that output into legacy rules.
    text = png_text_of_bytes(store.read_bytes(composite_handle))
    if COMPOSITE_POLICY_PNG_KEY in text:
        try:
            policy = json.loads(text[COMPOSITE_POLICY_PNG_KEY])
            stamp_schema = policy["receipt_schema"]
            supplied_schema = receipt.get("receipt_schema", 1)
            valid = (
                type(stamp_schema) is int
                and type(supplied_schema) is int
                and supplied_schema >= stamp_schema
            )
            if stamp_schema >= 4:
                valid = valid and policy["cut_quality_version"] == receipt.get(
                    "cut_quality", {}
                ).get("version")
        except (TypeError, ValueError, KeyError):
            valid = False
        check(
            "output_policy_stamp",
            valid,
            "receipt policy disagrees with the delivered PNG stamp",
        )
        if not valid:
            return report()
    persisted = store.load_receipt(composite_handle)
    if persisted is not None:
        stored_schema = persisted.get("receipt_schema", 1)
        supplied_schema = receipt.get("receipt_schema", 1)
        valid = (
            type(stored_schema) is int
            and type(supplied_schema) is int
            and supplied_schema >= stored_schema
        )
        check(
            "persisted_receipt_policy",
            valid,
            "supplied receipt downgrades the persisted policy",
        )
        if not valid:
            return report()

    foreground_handle = receipt["foreground_asset"]
    source_handle = receipt["source_asset"]

    # The assets the RECEIPT names must exist: a receipt pointing at
    # nothing is a failed receipt, not an exception.
    records: dict[str, AssetRecord] = {}
    for label, handle in (
        ("source", source_handle),
        ("foreground", foreground_handle),
    ):
        try:
            records[label] = store.get_record(handle)
            check(f"{label}_asset_resolves", True)
        except (KeyError, ValueError) as exc:
            check(f"{label}_asset_resolves", False, str(exc))
    if len(records) != 2:
        return report()
    source_record = records["source"]
    foreground_record = records["foreground"]

    # 1. Every stored file must still match the hashes recorded for it
    #    (file bytes, decoded pixels, colour profile) — the mask file
    #    included. Before this pass the mask's pinned hashes were
    #    compared against the mask's RECORD only, so a swapped mask
    #    file still verified (badass Gauntlet defect 2, GPT).
    integrity_targets = [
        ("source", source_handle),
        ("foreground", foreground_handle),
        ("composite", composite_handle),
    ]
    if receipt.get("mask_asset"):
        integrity_targets.append(("mask", receipt["mask_asset"]))
    recon_block = receipt.get("reconstruction")
    if not isinstance(recon_block, dict):
        recon_block = None
    if recon_block and recon_block.get("layer_asset"):
        integrity_targets.append(("reconstruction_layer", recon_block["layer_asset"]))
    if recon_block and recon_block.get("region_map_asset"):
        integrity_targets.append(
            ("reconstruction_region_map", recon_block["region_map_asset"])
        )
    for label, handle in integrity_targets:
        try:
            store.verify_integrity(handle)
            check(f"{label}_file_integrity", True)
        except (AssetIntegrityError, KeyError, ValueError) as exc:
            check(f"{label}_file_integrity", False, str(exc))

    # 1b. The receipt's own hashes must name THESE files. Step 1 only
    #     proves each file matches its own asset record; without this
    #     step, run A's receipt verifies against run B's composite
    #     whenever the numbers happen to reproduce, and a receipt
    #     whose output hash was edited still passes (architecture
    #     Gauntlet: Claude, GPT, Fable each reproduced a variant).
    check(
        "source_hash_matches_receipt",
        receipt.get("source_sha256") == source_record.sha256
        and receipt.get("source_pixel_sha256") == source_record.pixel_sha256,
        "the receipt's source hashes do not match the source asset's "
        "recorded hashes; this receipt was not issued for this source",
    )
    check(
        "foreground_hash_matches_receipt",
        receipt.get("foreground_sha256") == foreground_record.sha256
        and receipt.get("foreground_pixel_sha256") == foreground_record.pixel_sha256,
        "the receipt's foreground hashes do not match the foreground "
        "asset's recorded hashes",
    )
    if "color_profile_foreground_sha256" in receipt:
        # The receipt pins the foreground's colour profile too (v2);
        # grade the pin, do not just carry it. Absent in v1 receipts.
        check(
            "foreground_profile_matches_receipt",
            receipt.get("color_profile_foreground_sha256")
            == foreground_record.color_profile_sha256,
            "the receipt's foreground profile hash does not match "
            "the foreground asset's recorded profile",
        )
    check(
        "output_hash_matches_receipt",
        receipt.get("output_asset") == composite_handle
        and receipt.get("output_sha256") == composite_record.sha256
        and receipt.get("output_pixel_sha256") == composite_record.pixel_sha256,
        "the receipt does not name this composite (its output_asset / "
        "output hashes point elsewhere); this receipt was issued for "
        "a different composite, even if the files happen to be "
        "byte-identical",
    )
    if receipt.get("mask_asset"):
        if receipt.get("mask_sha256") or receipt.get("mask_pixel_sha256"):
            try:
                mask_record = store.get_record(receipt["mask_asset"])
                check(
                    "mask_hash_matches_receipt",
                    receipt.get("mask_sha256") == mask_record.sha256
                    and receipt.get("mask_pixel_sha256") == mask_record.pixel_sha256,
                    "the receipt's mask hashes do not match the mask "
                    "asset's recorded hashes",
                )
            except KeyError as exc:
                check("mask_hash_matches_receipt", False, str(exc))
        else:
            # A receipt that names a mask asset without pinning its
            # hashes: issued before mask pinning (the frozen replay
            # package's receipt is the live example; its manifest pins
            # every file's bytes instead). The strongest check
            # available is the mask file's integrity against its own
            # asset record — already run as mask_file_integrity in
            # step 1 — so this check mirrors that verdict. Receipts
            # draw issues today always pin the mask hashes and take
            # the strict branch above.
            check(
                "mask_asset_integrity",
                checks.get("mask_file_integrity", False),
                "the mask file does not match its asset record",
            )

    if recon_block and recon_block.get("layer_asset"):
        try:
            layer_record = store.get_record(recon_block["layer_asset"])
            check(
                "reconstruction_hash_matches_receipt",
                recon_block.get("layer_sha256") == layer_record.sha256
                and recon_block.get("layer_pixel_sha256") == layer_record.pixel_sha256,
                "the receipt's reconstruction layer hashes match the "
                "layer asset's sidecar record"
                if recon_block.get("layer_sha256") == layer_record.sha256
                and recon_block.get("layer_pixel_sha256") == layer_record.pixel_sha256
                else "the receipt's reconstruction layer hashes do "
                "not match the layer asset's sidecar record",
            )
        except KeyError as exc:
            check("reconstruction_hash_matches_receipt", False, str(exc))
        store.verify_integrity(recon_block["layer_asset"])
    if recon_block and recon_block.get("region_map_asset"):
        try:
            map_record = store.get_record(recon_block["region_map_asset"])
            check(
                "region_map_hash_matches_receipt",
                recon_block.get("region_map_sha256") == map_record.sha256
                and recon_block.get("region_map_pixel_sha256")
                == map_record.pixel_sha256,
                "the receipt's region map hashes match the map asset's sidecar record"
                if recon_block.get("region_map_sha256") == map_record.sha256
                and recon_block.get("region_map_pixel_sha256")
                == map_record.pixel_sha256
                else "the receipt's region map hashes do not match "
                "the map asset's sidecar record",
            )
        except KeyError as exc:
            check("region_map_hash_matches_receipt", False, str(exc))
        store.verify_integrity(recon_block["region_map_asset"])

    # 2. Decode the stored files fresh from disk and recount — the
    #    receipt's numbers must reproduce. A file that cannot be
    #    decoded is a failed verification, not a crash: the integrity
    #    checks above have usually already named the cause.
    decoded: tuple[Image.Image, Image.Image, Image.Image] | None = None
    try:
        decoded = (
            store.read_image(foreground_handle),
            store.read_image(composite_handle),
            store.read_image(source_handle),
        )
        check("files_decodable", True)
    except Exception as exc:  # noqa: BLE001 - a verifier boundary:
        # any decode failure (corrupt bytes, missing file, unsupported
        # encoding) is evidence against the receipt, reported as such.
        check("files_decodable", False, f"{type(exc).__name__}: {exc}")
    if decoded is not None:
        foreground, composite_image, source_image = decoded
        if foreground.size == source_image.size:
            from .cut_quality import grade_cut

            recomputed["cut_quality"] = grade_cut(
                source_image, foreground.getchannel("A")
            )
        check(
            "foreground_pixel_hash",
            pixel_hash_of_image(foreground) == receipt["foreground_pixel_sha256"],
            "decoded foreground pixels do not match the receipt's pinned hash",
        )
        check(
            "composite_pixel_hash",
            pixel_hash_of_image(composite_image) == composite_record.pixel_sha256,
            "decoded composite pixels do not match the stored asset record",
        )
        if foreground.size != composite_image.size:
            check(
                "recount",
                False,
                f"foreground is {foreground.size}, composite is "
                f"{composite_image.size}; sizes must match exactly",
            )
        else:
            counts = _measure(foreground, composite_image)
            recomputed.update(counts)
            for field in (
                "changed_opaque_pixels",
                "opaque_pixels",
                "edge_band_pixels",
                "transparent_pixels",
                "mask_pixels_total",
                "edge_band_max_width_px",
            ):
                check(
                    f"recount_{field}",
                    counts[field] == receipt[field],
                    f"receipt says {receipt[field]}, recount from disk "
                    f"finds {counts[field]}",
                )
            check(
                "recount_opaque_fraction",
                abs(counts["opaque_fraction"] - receipt["opaque_fraction"]) < 1e-9,
                f"receipt says {receipt['opaque_fraction']}, recount "
                f"from disk finds {counts['opaque_fraction']}",
            )

        # 2b. The verdict itself, stated as checks rather than
        #     implied by agreement: a pass requires ZERO changed
        #     pixels — an honest receipt reporting a real change
        #     reproduces perfectly under the recount checks above and
        #     must still fail — and POSITIVE coverage, because a
        #     receipt covering no opaque pixels vouches for nothing
        #     (architecture Gauntlet, GPT + Claude).
        check(
            "zero_changed_pixels",
            recomputed.get("changed_opaque_pixels") == 0
            and receipt.get("changed_opaque_pixels") == 0,
            f"changed opaque pixels: receipt says "
            f"{receipt.get('changed_opaque_pixels')}, recount from "
            f"disk finds {recomputed.get('changed_opaque_pixels')}; "
            "the Fidelity Lock claim requires exactly 0",
        )
        check(
            "positive_coverage",
            (recomputed.get("opaque_pixels") or 0) > 0
            and (receipt.get("opaque_pixels") or 0) > 0,
            "the receipt covers 0 fully opaque foreground pixels; "
            "there is no product evidence to verify",
        )

        # The stored foreground must BE the source image wherever
        # it is fully opaque. A foreground that differs from its
        # source, fabricated product pixels under a valid lineage,
        # otherwise passes every check: its own hashes are
        # self-consistent, the server-side ancestry guard reads the
        # mask's pixels rather than the foreground's, and the
        # composite-versus-foreground recount still reads 0 changed.
        if foreground.size != source_image.size:
            check(
                "foreground_matches_source",
                False,
                f"foreground is {foreground.size} but the source "
                f"photo is {source_image.size}",
            )
        else:
            fg_arr = np.frombuffer(foreground.tobytes(), dtype=np.uint8).reshape(-1, 4)
            src_arr = np.frombuffer(source_image.tobytes(), dtype=np.uint8).reshape(
                -1, 4
            )
            solid = fg_arr[:, 3] == 255
            same = bool(np.array_equal(fg_arr[solid], src_arr[solid]))
            check(
                "foreground_matches_source",
                same,
                "every fully opaque foreground pixel matches the source photo"
                if same
                else "the foreground differs from the source photo "
                "on fully opaque pixels; the product layer is not "
                "the photograph it claims to be",
            )

        # Paper recounts: the layer's pixels and their overlap with
        # the product, measured on the stored files, plus the region
        # map partition: the map must cover exactly the paper, and
        # each class's pixels must equal the receipt's per-region
        # counts.
        if recon_block and recon_block.get("layer_asset"):
            try:
                layer_image = store.read_image(recon_block["layer_asset"])
                recounts = _measure_reconstruction(foreground, layer_image)
                recomputed["reconstruction_pixels"] = recounts["reconstruction_pixels"]
                recomputed["reconstruction_overlap_product_pixels"] = recounts[
                    "reconstruction_overlap_product_pixels"
                ]
                check(
                    "recount_reconstruction_pixels",
                    recounts["reconstruction_pixels"]
                    == recon_block["reconstruction_pixels"],
                    f"stored layer holds "
                    f"{recounts['reconstruction_pixels']} paper "
                    f"pixels; receipt says "
                    f"{recon_block['reconstruction_pixels']}",
                )
                check(
                    "recount_overlap_zero",
                    recounts["reconstruction_overlap_product_pixels"] == 0,
                    "no paper pixel sits under any foreground alpha"
                    if recounts["reconstruction_overlap_product_pixels"] == 0
                    else f"{recounts['reconstruction_overlap_product_pixels']} "
                    "paper pixels sit under foreground alpha; paper "
                    "there changes the delivered product edge",
                )
                if recon_block.get("region_map_asset"):
                    map_values = np.frombuffer(
                        store.read_image(recon_block["region_map_asset"])
                        .convert("L")
                        .tobytes(),
                        dtype=np.uint8,
                    )
                    layer_alpha = np.frombuffer(
                        layer_image.getchannel("A").tobytes(), dtype=np.uint8
                    )
                    partition_ok = bool(np.array_equal(map_values > 0, layer_alpha > 0))
                    # Per-class totals: several regions can share a
                    # class (two legs are both supports), so the map
                    # count for a code is graded against the SUM of
                    # that class's region counts, and any code
                    # outside the known set fails the partition.
                    known_codes = list(REGION_CLASS_CODES.values())
                    class_ok = not bool(
                        np.count_nonzero(
                            (map_values != 0) & ~np.isin(map_values, known_codes)
                        )
                    )
                    for cls, code in REGION_CLASS_CODES.items():
                        expected = sum(
                            r["pixels"]
                            for r in recon_block["regions"]
                            if r["class"] == cls
                        )
                        if int(np.count_nonzero(map_values == code)) != expected:
                            class_ok = False
                    check(
                        "region_map_partition",
                        partition_ok and class_ok,
                        "the region map covers exactly the paper "
                        "pixels and each class count matches"
                        if partition_ok and class_ok
                        else "the region map disagrees with the "
                        "layer's paper pixels or the per-class counts",
                    )
            except Exception as exc:  # noqa: BLE001
                check(
                    "reconstruction_files_decodable",
                    False,
                    f"reconstruction assets could not be decoded: {exc}",
                )

        # 3. Colour-profile identity, re-derived from the files: the
        #    profile the receipt names must be the profile in the
        #    files, and source and output profiles must be identical.
        source_profile = color_profile_sha256_of_image(source_image)
        output_profile = color_profile_sha256_of_image(composite_image)
        recomputed["color_profile_source_sha256"] = source_profile
        recomputed["color_profile_output_sha256"] = output_profile
        check(
            "color_profile_matches_receipt",
            source_profile == receipt["color_profile_source_sha256"]
            and output_profile == receipt["color_profile_output_sha256"],
            "profiles decoded from the files differ from the "
            "receipt's recorded profile hashes",
        )
        preserved = source_profile == output_profile
        recomputed["color_profile_preserved"] = preserved
        check(
            "color_profile_preserved",
            preserved and receipt["color_profile_preserved"] is True,
            "the delivered composite's colour profile differs from "
            "the source photo's; identical pixel values would "
            "display as different colours",
        )

        # 4. Whole-delivery reproduction: rebuilding the composite
        #    from the stored plate, the stored paper layer, and the
        #    stored foreground must reproduce the delivered file
        #    pixel for pixel. This is the check that makes the whole
        #    frame accountable: any pixel painted onto the delivery
        #    outside the three stored layers breaks the identity.
        #    Asset plates only; a local placeholder plate carries no
        #    asset, so the check is recorded as a named skip in the
        #    recomputed values, never silently as a pass.
        if receipt.get("plate_asset"):
            try:
                plate_image = store.read_image(receipt["plate_asset"])
                layer_for_rebuild = (
                    store.read_image(recon_block["layer_asset"])
                    if recon_block and recon_block.get("layer_asset")
                    else None
                )
                rebuilt, _, _ = composite_images(
                    foreground, plate_image, layer_for_rebuild
                )
                reproduced = rebuilt.tobytes() == composite_image.tobytes()
                check(
                    "layer_reproduction",
                    reproduced,
                    "the delivered file equals plate, then paper, "
                    "then product, composited from the stored layers"
                    if reproduced
                    else "the delivered file is not the composite of "
                    "its stored plate, paper layer, and foreground; "
                    "pixels outside the three layers are present",
                )
            except Exception as exc:  # noqa: BLE001
                check(
                    "layer_reproduction",
                    False,
                    f"rebuild from stored layers raised {type(exc).__name__}: {exc}",
                )
        else:
            recomputed["layer_reproduction"] = (
                "skipped: no plate asset (local placeholder plate)"
            )

    if receipt.get("receipt_schema") == 4 and decoded is not None:
        try:
            from .quality_receipt import verify_quality

            quality_data, quality_checks = verify_quality(
                store, foreground_handle, receipt
            )
            recomputed.update(quality_data)
            for name, (ok, detail) in quality_checks.items():
                check(name, ok, detail)
        except Exception as exc:
            check("schema4_quality_recomputed", False, f"{type(exc).__name__}: {exc}")

    return report()
