//! SAM wire-format tests: canned model responses (Python suite
//! vectors, with frame hashes computed by the official parser) plus
//! extra one-bit payloads encoded by the official encoder in Python.

use agenthand::image::{sha256_hex, GrayImage, RgbaImage};
use agenthand::sam::{parse_sam_masks, DecodedMask};
use agenthand::segmentation::{assess_mask, extract_foreground, mask_iou, review_mask};

const GOOD_TEXT: &str =
    "<0f>0<|box;x1=0;y1=0;x2=3;y2=5;w=8;h=6|><|mask;x=0;y=0;data=6,4,!!!!!'y8_cbF.|>";
const FULL_TEXT: &str =
    "<0f>0<|box;x1=0;y1=0;x2=7;y2=5;w=8;h=6|><|mask;x=0;y=0;data=6,8,!!!!!'y:A%B`S|>";
const FRAG_TEXT: &str =
    "<0f>0<|box;x1=0;y1=0;x2=7;y2=5;w=8;h=6|><|mask;x=0;y=0;data=6,8,!!!!!+dhFaV_wsyCio|>";
const ZERO_TEXT: &str =
    "<0f>0<|box;x1=0;y1=0;x2=3;y2=5;w=8;h=6|><|mask;x=0;y=0;data=6,4,!!!!!&!!!!!|>";
const TWO_RECORDS_TEXT: &str = "<0f>0<|box;x1=6;y1=4;x2=7;y2=5;w=8;h=6|><|mask;x=0;y=0;data=2,2,!!!!!&t.SKi|>,1<|box;x1=0;y1=0;x2=3;y2=5;w=8;h=6|><|mask;x=0;y=0;data=6,4,!!!!!'y8_cbF.|>";
const DOCS_LOSSLESS_TEXT: &str = "<0f>0<|box;x1=211;y1=228;x2=270;y2=254;w=320;h=334|><|mask;x=0;y=0;data=27,60,~!!!!M!0c[0o91w?q1!pIH4pPRVp2B3'7`e.ioeAf6-k/#Xd8%dX9x(|>";

fn frame_gray(mask: &DecodedMask) -> GrayImage {
    GrayImage {
        width: mask.frame_width as u32,
        height: mask.frame_height as u32,
        pixels: mask.image.clone(),
        icc_profile: None,
    }
}

#[test]
fn good_mask_decodes_to_the_left_half() {
    let masks = parse_sam_masks(GOOD_TEXT, 8, 6).unwrap();
    assert_eq!(masks.len(), 1);
    let m = &masks[0];
    assert_eq!(m.object_id, "0");
    assert_eq!(m.bounds, (0, 0, 4, 6));
    assert_eq!(m.mask_pixels, 24);
    // Frame hash computed by the official Python parser.
    assert_eq!(
        sha256_hex(&m.image),
        "4ae5ce3aabc6e65d0530988450363a48d5f4bdd43dc00d2b4b96bac6792c032a"
    );
    let qa = assess_mask(&frame_gray(m));
    assert!(qa.accepted);
    assert_eq!(qa.mask_pixels, 24);
    assert_eq!(qa.coverage, 0.5);
    assert_eq!(qa.components, 1);
    assert_eq!(qa.dominant_fraction, 1.0);
}

#[test]
fn good_mask_iou_is_one_against_the_golden() {
    let masks = parse_sam_masks(GOOD_TEXT, 8, 6).unwrap();
    let mut golden = GrayImage {
        width: 8,
        height: 6,
        pixels: vec![0; 48],
        icc_profile: None,
    };
    for y in 0..6usize {
        for x in 0..4usize {
            golden.pixels[y * 8 + x] = 255;
        }
    }
    let iou = mask_iou(&frame_gray(&masks[0]), &golden).unwrap();
    assert!((iou - 1.0).abs() < 1e-12);
}

#[test]
fn full_frame_mask_is_rejected() {
    let masks = parse_sam_masks(FULL_TEXT, 8, 6).unwrap();
    assert_eq!(masks[0].mask_pixels, 48);
    assert_eq!(
        sha256_hex(&masks[0].image),
        "80a76a18acf8cb64fec3a659ffc4bab4a87cd9a6fde4dab2161a8751d136c9d2"
    );
    let qa = assess_mask(&frame_gray(&masks[0]));
    assert!(!qa.accepted);
    assert_eq!(qa.rejection, Some("full_frame"));
    assert_eq!(qa.coverage, 1.0);
}

#[test]
fn fragmented_mask_is_rejected() {
    let masks = parse_sam_masks(FRAG_TEXT, 8, 6).unwrap();
    let qa = assess_mask(&frame_gray(&masks[0]));
    assert!(!qa.accepted);
    assert_eq!(qa.rejection, Some("fragmented"));
    assert_eq!(qa.components, 2);
    assert_eq!(qa.dominant_fraction, 0.5);
}

#[test]
