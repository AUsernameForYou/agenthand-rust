/// Extra one-bit payloads generated by the official Python encoder
/// (_encode_raster) over seeded random rasters; the Rust decoder
/// must reproduce the exact raster bytes.
#[test]
fn official_encoder_payloads_round_trip() {
    let cases: [(&str, u32, u32, &str); 3] = [
        (
            "!!!!!4LdavHkbdY`cyJkz[]xYHn{",
            13,
            9,
            "3b779fc804c5dd19c69d9d840900f1923fa347b106d8533a78c60b5bf239b323",
        ),
        (
            "!!!!!lG2TMrMZelv]tL=jlw[Q[_.J]jp16J)u4$*sW{7[f7/#/='Ow1$Z!rg@(V/jBHFesOjH`4CFIcvI7lx7sYsu0UNP",
            31,
            17,
            "5cf0e28ea1bb233cb99029f310a88e3461551b04dbcf19041f0be228145996b6",
        ),
        (
            "!!!!%rL^.Eg#%9p(aj%PBsa'[2'm(i8u3^YJt^8=@TR!)`:RY]?wdF:Cdu4mrdZTBijUt-/vj-25tsPO7XA[r_hIA{ODPI`sx$6T`#T=!:fIgH_'G!H1q{GO:c]A6Gj9Xk?NzUlvFsA2Ba4Os`8y?HUdKjnr]RgNZuVRM.1hvF#N#/IF_gfrZS4Xi#&q_+.C?jURFDw!BxqUraRMJ=$*oRt@sxc._.1Wngoxt?ZG$f6t!U^J`]cb4(]a?PLTP{--G9W0{xV+Bb@zY_(WXjloeivfZRFuYsMF8=jsfQAMV=t&*^NI:Vm^XGN/=]@)JyPe6R2y(4h+ZUIF%/EM+7#no0d'!.7fc!b((D7&nvSd!srW!-3*Qg@m0]UG3hX$76%dCCQs/C)Iv!:5=AOh+G3Im@hl$-3-_JBW%zc",
            64,
            48,
            "ce210f58fddbfb594f8bbfc123f743a83142afafe5d0318ddffec0633220933a",
        ),
    ];
    for (payload, w, h, expected_sha) in cases {
        let text = format!(
            "<0f>0<|box;x1=0;y1=0;x2={};y2={};w={w};h={h}|><|mask;x=0;y=0;data={h},{w},{payload}|>",
            w - 1,
            h - 1
        );
        let masks = parse_sam_masks(&text, w as usize, h as usize).unwrap();
        assert_eq!(masks.len(), 1, "payload {payload:.20}…");
        // The Python reference hashed the 0/1 box-local raster; the
        // Rust frame is the same raster as 0/255 (full-frame boxes
        // here), so normalize before hashing.
        let normalized: Vec<u8> = masks[0]
            .image
            .iter()
            .map(|&v| if v > 0 { 1 } else { 0 })
            .collect();
        assert_eq!(sha256_hex(&normalized), expected_sha);
    }
}

#[test]
fn extract_foreground_keeps_source_pixels_byte_exact() {
    let source = RgbaImage::solid(8, 6, [200, 30, 30, 255]);
    let masks = parse_sam_masks(GOOD_TEXT, 8, 6).unwrap();
    let fg = extract_foreground(&source, &frame_gray(&masks[0]));
    assert_eq!(fg.pixel(0, 0), [200, 30, 30, 255]);
    assert_eq!(fg.pixel(3, 5), [200, 30, 30, 255]);
    assert_eq!(fg.pixel(4, 0), [0, 0, 0, 0]);
    assert_eq!(fg.pixel(7, 5), [0, 0, 0, 0]);
}

/// Regression: a record whose box is WIDER than its box-local raster.
/// SAM returned exactly this shape for the border-touching fridge mask
/// on IMG_1351 (real run, 2026-10-31): the bounds outrun the raster and
/// the old place_in_frame indexed past the end of the raster and
/// panicked (sam.rs index out of bounds), killing the server. The
/// Python reference places the same record through PIL crop, which
/// zero-pads the overhang: out-of-raster columns read as 0.
#[test]
fn box_wider_than_raster_places_with_zero_padding() {
    // GOOD_TEXT's 4x6 all-on raster, but the box claims the full 8-wide
    // frame. Placement must equal the good mask's frame exactly.
    let text = "<0f>0<|box;x1=0;y1=0;x2=7;y2=5;w=8;h=6|><|mask;x=0;y=0;data=6,4,!!!!!'y8_cbF.|>";
    let masks = parse_sam_masks(text, 8, 6).unwrap();
    assert_eq!(masks.len(), 1);
    assert_eq!(masks[0].mask_pixels, 24);
    assert_eq!(
        sha256_hex(&masks[0].image),
        "4ae5ce3aabc6e65d0530988450363a48d5f4bdd43dc00d2b4b96bac6792c032a"
    );
}

/// Regression: a record whose box is TALLER than its raster (the other
/// overhang direction of the same panic).
#[test]
fn box_taller_than_raster_places_with_zero_padding() {
    // GOOD_TEXT's 4x6 raster in a 4x8 box inside an 8x8 frame: the top
    // six rows land, the two overhang rows read as 0.
    let text = "<0f>0<|box;x1=0;y1=0;x2=3;y2=7;w=8;h=8|><|mask;x=0;y=0;data=6,4,!!!!!'y8_cbF.|>";
    let masks = parse_sam_masks(text, 8, 8).unwrap();
    assert_eq!(masks.len(), 1);
    assert_eq!(masks[0].mask_pixels, 24);
    let img = &masks[0].image;
    for y in 0..8usize {
        for x in 0..8usize {
            let expected = if y < 6 && x < 4 { 255 } else { 0 };
            assert_eq!(img[y * 8 + x], expected, "pixel ({x},{y})");
        }
    }
}

/// Regression: the fridge shape itself — a full-frame, border-touching
/// box carrying a much smaller raster. Placement must not panic; only
/// the raster's own extent lands.
#[test]
fn full_frame_box_with_small_raster_does_not_panic() {
    // The all-on 2x2 raster from TWO_RECORDS_TEXT under a box covering
    // the whole 8x6 frame (touches every border).
    let text = "<0f>0<|box;x1=0;y1=0;x2=7;y2=5;w=8;h=6|><|mask;x=0;y=0;data=2,2,!!!!!&t.SKi|>";
    let masks = parse_sam_masks(text, 8, 6).unwrap();
    assert_eq!(masks.len(), 1);
    assert_eq!(masks[0].mask_pixels, 4);
    let img = &masks[0].image;
    for y in 0..6usize {
        for x in 0..8usize {
            let expected = if y < 2 && x < 2 { 255 } else { 0 };
            assert_eq!(img[y * 8 + x], expected, "pixel ({x},{y})");
        }
    }
}

#[test]
fn review_mask_reports_bounds_fill_and_edge_touches() {
    let masks = parse_sam_masks(GOOD_TEXT, 8, 6).unwrap();
    let review = review_mask(&frame_gray(&masks[0]));
    assert_eq!(review["mask_pixels"], 24);
    assert_eq!(review["coverage"], 0.5);
    assert_eq!(review["bbox"], serde_json::json!([0, 0, 4, 6]));
    assert_eq!(review["bbox_fill"], 1.0);
    assert_eq!(
        review["touches_frame_edges"],
        serde_json::json!(["left", "top", "bottom"])
    );
    assert_eq!(review["warnings"], serde_json::json!([]));
}

#[test]
fn absurd_mask_dimensions_are_skipped_not_allocated() {
    // Regression (2026-10-31 adversarial pass): the mask raster is
    // allocated at the API-declared dimensions. A record claiming
    // 100000x100000 (10^10 px) aborted the process on allocation
    // before the area ceiling existed; it must now be skipped like
    // any other invalid payload.
    let text =
        "<0f>0<|box;x1=0;y1=0;x2=3;y2=5;w=8;h=6|><|mask;x=0;y=0;data=100000,100000,!!!!!'y8_cbF.|>";
    assert!(parse_sam_masks(text, 8, 6).unwrap().is_empty());
}

#[test]
fn oversized_mask_rasters_are_rejected_before_decoding() {
    use agenthand::sam::{decode_mask_to_raster, MaskEncoding, SegmentationMask};
    // Product overflows u64 entirely.
    let mask = SegmentationMask {
        encoding: MaskEncoding::OneBit,
        payload: "!AAAA".to_string(),
        width: i64::MAX,
        height: 2,
    };
    assert!(decode_mask_to_raster(&mask).is_err());
    // Product fits but exceeds the ceiling (10^10 px).
    let mask = SegmentationMask {
        encoding: MaskEncoding::Lossless,
        payload: "~AAAA".to_string(),
        width: 100_000,
        height: 100_000,
    };
    assert!(decode_mask_to_raster(&mask).is_err());
}
