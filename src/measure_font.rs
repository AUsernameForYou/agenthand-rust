//! A 5 x 7 bitmap font (2 descender rows) for the garment diagram.
//! Code-drawn on purpose: the diagram is produced with no font files,
//! no crates and no model calls. Each glyph is up to nine rows of five
//! columns; row 6 sits on the baseline, rows 7 and 8 are descenders.

pub const GLYPH_W: usize = 5;

/// Rows of one glyph ('#' = ink). Unknown characters draw as '?'.
pub fn glyph(ch: char) -> [&'static str; 9] {
    const B: &str = "     ";
    let g7 = |r: [&'static str; 7]| -> [&'static str; 9] {
        [r[0], r[1], r[2], r[3], r[4], r[5], r[6], B, B]
    };
    match ch {
        ' ' => [B; 9],
        '0' => g7([
            " ### ", "#   #", "#  ##", "# # #", "##  #", "#   #", " ### ",
        ]),
        '1' => g7([
            "  #  ", " ##  ", "  #  ", "  #  ", "  #  ", "  #  ", " ### ",
        ]),
        '2' => g7([
            " ### ", "#   #", "    #", "   # ", "  #  ", " #   ", "#####",
        ]),
        '3' => g7([
            "#####", "   # ", "  #  ", "   # ", "    #", "#   #", " ### ",
        ]),
        '4' => g7([
            "   # ", "  ## ", " # # ", "#  # ", "#####", "   # ", "   # ",
        ]),
        '5' => g7([
            "#####", "#    ", "#### ", "    #", "    #", "#   #", " ### ",
        ]),
        '6' => g7([
            "  ## ", " #   ", "#    ", "#### ", "#   #", "#   #", " ### ",
        ]),
        '7' => g7([
            "#####", "    #", "   # ", "  #  ", " #   ", " #   ", " #   ",
        ]),
        '8' => g7([
            " ### ", "#   #", "#   #", " ### ", "#   #", "#   #", " ### ",
        ]),
        '9' => g7([
            " ### ", "#   #", "#   #", " ####", "    #", "   # ", " ##  ",
        ]),
        'A' => g7([
            " ### ", "#   #", "#   #", "#####", "#   #", "#   #", "#   #",
        ]),
        'B' => g7([
            "#### ", "#   #", "#   #", "#### ", "#   #", "#   #", "#### ",
        ]),
        'C' => g7([
            " ### ", "#   #", "#    ", "#    ", "#    ", "#   #", " ### ",
        ]),
        'D' => g7([
            "###  ", "#  # ", "#   #", "#   #", "#   #", "#  # ", "###  ",
        ]),
        'E' => g7([
            "#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#####",
        ]),
        'F' => g7([
            "#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#    ",
        ]),
        'G' => g7([
            " ### ", "#   #", "#    ", "# ###", "#   #", "#   #", " ####",
        ]),
        'H' => g7([
            "#   #", "#   #", "#   #", "#####", "#   #", "#   #", "#   #",
        ]),
        'I' => g7([
            " ### ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", " ### ",
        ]),
        'J' => g7([
            "  ###", "   # ", "   # ", "   # ", "   # ", "#  # ", " ##  ",
        ]),
        'K' => g7([
            "#   #", "#  # ", "# #  ", "##   ", "# #  ", "#  # ", "#   #",
        ]),
        'L' => g7([
            "#    ", "#    ", "#    ", "#    ", "#    ", "#    ", "#####",
        ]),
        'M' => g7([
            "#   #", "## ##", "# # #", "# # #", "#   #", "#   #", "#   #",
        ]),
        'N' => g7([
            "#   #", "#   #", "##  #", "# # #", "#  ##", "#   #", "#   #",
        ]),
        'O' => g7([
            " ### ", "#   #", "#   #", "#   #", "#   #", "#   #", " ### ",
        ]),
        'P' => g7([
            "#### ", "#   #", "#   #", "#### ", "#    ", "#    ", "#    ",
        ]),
        'Q' => g7([
            " ### ", "#   #", "#   #", "#   #", "# # #", "#  # ", " ## #",
        ]),
        'R' => g7([
            "#### ", "#   #", "#   #", "#### ", "# #  ", "#  # ", "#   #",
        ]),
        'S' => g7([
            " ####", "#    ", "#    ", " ### ", "    #", "    #", "#### ",
        ]),
        'T' => g7([
            "#####", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ",
        ]),
        'U' => g7([
            "#   #", "#   #", "#   #", "#   #", "#   #", "#   #", " ### ",
        ]),
        'V' => g7([
            "#   #", "#   #", "#   #", "#   #", "#   #", " # # ", "  #  ",
        ]),
        'W' => g7([
            "#   #", "#   #", "#   #", "# # #", "# # #", "# # #", " # # ",
        ]),
        'X' => g7([
            "#   #", "#   #", " # # ", "  #  ", " # # ", "#   #", "#   #",
        ]),
        'Y' => g7([
            "#   #", "#   #", " # # ", "  #  ", "  #  ", "  #  ", "  #  ",
        ]),
        'Z' => g7([
            "#####", "    #", "   # ", "  #  ", " #   ", "#    ", "#####",
        ]),
        'a' => g7([B, B, " ### ", "    #", " ####", "#   #", " ####"]),
        'b' => g7([
            "#    ", "#    ", "# ## ", "##  #", "#   #", "#   #", "#### ",
        ]),
        'c' => g7([B, B, " ### ", "#    ", "#    ", "#   #", " ### "]),
        'd' => g7([
            "    #", "    #", " ## #", "#  ##", "#   #", "#   #", " ####",
        ]),
        'e' => g7([B, B, " ### ", "#   #", "#####", "#    ", " ### "]),
        'f' => g7([
            "  ## ", " #  #", " #   ", "###  ", " #   ", " #   ", " #   ",
        ]),
        'g' => [
            B, B, " ####", "#   #", "#   #", "#   #", " ####", "    #", " ### ",
        ],
        'h' => g7([
            "#    ", "#    ", "# ## ", "##  #", "#   #", "#   #", "#   #",
        ]),
        'i' => g7(["  #  ", B, " ##  ", "  #  ", "  #  ", "  #  ", " ### "]),
        'j' => [
            "   # ", B, "  ## ", "   # ", "   # ", "   # ", "   # ", "#  # ", " ##  ",
        ],
        'k' => g7([
            "#    ", "#    ", "#  # ", "# #  ", "##   ", "# #  ", "#  # ",
        ]),
        'l' => g7([
            " ##  ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", " ### ",
        ]),
        'm' => g7([B, B, "## # ", "# # #", "# # #", "#   #", "#   #"]),
        'n' => g7([B, B, "# ## ", "##  #", "#   #", "#   #", "#   #"]),
        'o' => g7([B, B, " ### ", "#   #", "#   #", "#   #", " ### "]),
        'p' => [
            B, B, "#### ", "#   #", "#   #", "#   #", "#### ", "#    ", "#    ",
        ],
        'q' => [
            B, B, " ####", "#   #", "#   #", "#   #", " ####", "    #", "    #",
        ],
        'r' => g7([B, B, "# ## ", "##  #", "#    ", "#    ", "#    "]),
        's' => g7([B, B, " ####", "#    ", " ### ", "    #", "#### "]),
        't' => g7([
            " #   ", " #   ", "###  ", " #   ", " #   ", " #  #", "  ## ",
        ]),
        'u' => g7([B, B, "#   #", "#   #", "#   #", "#  ##", " ## #"]),
        'v' => g7([B, B, "#   #", "#   #", "#   #", " # # ", "  #  "]),
        'w' => g7([B, B, "#   #", "#   #", "# # #", "# # #", " # # "]),
        'x' => g7([B, B, "#   #", " # # ", "  #  ", " # # ", "#   #"]),
        'y' => [
            B, B, "#   #", "#   #", "#   #", "#   #", " ####", "    #", " ### ",
        ],
        'z' => g7([B, B, "#####", "   # ", "  #  ", " #   ", "#####"]),
        '.' => g7([B, B, B, B, B, " ##  ", " ##  "]),
        ',' => [B, B, B, B, B, " ##  ", " ##  ", "  #  ", " #   "],
        ':' => g7([B, " ##  ", " ##  ", B, " ##  ", " ##  ", B]),
        ';' => [
            B, " ##  ", " ##  ", B, " ##  ", " ##  ", "  #  ", " #   ", B,
        ],
        '(' => g7([
            "   # ", "  #  ", " #   ", " #   ", " #   ", "  #  ", "   # ",
        ]),
        ')' => g7([
            " #   ", "  #  ", "   # ", "   # ", "   # ", "  #  ", " #   ",
        ]),
        '-' => g7([B, B, B, " ### ", B, B, B]),
        '\u{2013}' => g7([B, B, B, "#####", B, B, B]),
        '\u{00b1}' => g7(["  #  ", "  #  ", "#####", "  #  ", "  #  ", B, "#####"]),
        '\u{00d7}' => g7([B, "#   #", " # # ", "  #  ", " # # ", "#   #", B]),
        '%' => g7([
            "##   ", "##  #", "   # ", "  #  ", " #   ", "#  ##", "   ##",
        ]),
        '/' => g7([B, "    #", "   # ", "  #  ", " #   ", "#    ", B]),
        '+' => g7([B, "  #  ", "  #  ", "#####", "  #  ", "  #  ", B]),
        '=' => g7([B, B, "#####", B, "#####", B, B]),
        '\'' => g7(["  #  ", "  #  ", " #   ", B, B, B, B]),
        '~' => g7([B, B, " #   ", "# # #", "   # ", B, B]),
        '!' => g7(["  #  ", "  #  ", "  #  ", "  #  ", "  #  ", B, "  #  "]),
        '<' => g7([
            "   # ", "  #  ", " #   ", "#    ", " #   ", "  #  ", "   # ",
        ]),
        '>' => g7([
            " #   ", "  #  ", "   # ", "    #", "   # ", "  #  ", " #   ",
        ]),
        _ => g7([" ### ", "#   #", "    #", "   # ", "  #  ", B, "  #  "]),
    }
}
